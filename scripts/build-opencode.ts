#!/usr/bin/env bun
import solid from "@opentui/solid/bun-plugin";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const artifact = join(root, "opencode", "tui.generated.js");
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) throw new Error("Usage: bun scripts/build-opencode.ts [--check]");

const result = await Bun.build({
  entrypoints: [join(root, "opencode", "tui.tsx")],
  root,
  target: "bun",
  packages: "external",
  plugins: [solid],
});
if (!result.success) throw new AggregateError(result.logs, "OpenCode TUI build failed");
if (result.outputs.length !== 1) throw new Error("Expected one compiled OpenCode TUI entrypoint");
const generated = `// Generated by scripts/build-opencode.ts. Edit the TypeScript sources instead.\n${await result.outputs[0]!.text()}`;
if (generated.includes(root)) throw new Error("Compiled TUI contains an absolute checkout path");

if (args[0] === "--check") {
  if (readFileSync(artifact, "utf8") !== generated) throw new Error("Compiled OpenCode TUI is stale. Run just build-opencode.");
  console.log("Compiled OpenCode TUI matches its sources.");
} else {
  writeFileSync(artifact, generated);
  console.log("Built opencode/tui.generated.js with external host dependencies.");
}
